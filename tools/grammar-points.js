// A form plus endings, each a kana string or [spelling, reading] [て form + [下さい, ください] = 話して下さい / はなしてください].
const plus = (a, ends, g, pol) => (a ? ends.map((e) => (typeof e === "string" ? [e, e] : e)).map(([w, r]) => ({ w: a.w + w, r: a.r + r, g, pol })) : []);
const cut = (a, n) => a && { w: a.w.slice(0, -n), r: a.r.slice(0, -n) };
const kindOf = (word) => {
  const c = word && classOf(word);
  return !c ? "noun" : c === "adj-na" ? "na" : c.startsWith("adj") ? "i" : "verb";
};
// The plain forms a clause ends in before ので, んです and でしょう, each tagged with its tense [行った = past; 静かじゃない = not].
const TENSES = ["now", "past", "not", "notpast"];
const plain = (f, word) => {
  const k = kindOf(word);
  const tag = (list) => list.map((a, i) => a && { ...a, t: TENSES[i] }).filter(Boolean);
  if (k === "na") return tag([{ w: word.w, r: word.r, noun: true }, f("ta"), f("nai"), f("nakatta")]);
  if (k === "noun") return tag([{ w: word.w, r: word.r, noun: true }, ...["だった", "じゃない", "じゃなかった"].map((e) => ({ w: word.w + e, r: word.r + e }))]);
  const forms = tag([base(word), f("ta"), f("nai"), f("nakatta")]);
  // A する noun is a noun too [留守だった as well as 留守した].
  return base(word).w === word.w ? forms : [...forms, ...plain(null, { ...word, pos: ["n"] }).map((a) => ({ ...a, t: "noun-" + a.t }))];
};
const fixed = (ends, g) => ends.flatMap(([w, r, pol]) => [{ w, r, g, pol }]);

